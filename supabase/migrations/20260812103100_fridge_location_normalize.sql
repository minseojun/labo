-- ============================================================================
-- LABO — 냉장고 칸 이름을 숫자 기준으로 통일
--
-- "칸/위치"가 자유 입력이라 "3", "3번칸", "3번 칸", "칸3"이 전부 다른 칸으로
-- 취급됐음(문자열이 완전히 같아야 같은 칸으로 묶임). 프론트(FridgeMapScreen)는
-- 이제 저장할 때 위치 문자열에서 숫자를 찾아 "N번 칸" 형태로 정규화해서 저장함
-- — 숫자가 없는 자유 텍스트(예: "문쪽", "맨 아래")는 그대로 둠.
--
-- 이 마이그레이션은 이미 저장돼 있던 기존 데이터도 같은 규칙으로 맞춰줌.
-- 숫자가 하나라도 포함된 위치 문자열만 대상으로 하고, 그 안의 첫 번째 숫자를
-- 뽑아 "N번 칸"으로 바꿈. 이미 "N번 칸" 형태인 행은 다시 돌려도 "N번 칸" 그대로라
-- 안전하게 재실행 가능함(멱등).
-- ============================================================================

update fridge_items
set location = (regexp_match(location, '\d+'))[1] || '번 칸'
where location ~ '\d'
  and location <> (regexp_match(location, '\d+'))[1] || '번 칸';
